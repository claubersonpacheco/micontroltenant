            </p>

            <h2>1. Datos que recopilamos</h2>
            <p>
                Nuestro sistema solo recopila los datos necesarios para elaborar y enviar presupuestos, así como para mantener la comunicación contigo. Los datos pueden incluir:
            </p>
            <ul>
                <li>Datos de contacto: nombre, apellidos, correo electrónico y número de teléfono.</li>
                <li>Datos del pedido: descripción del servicio, detalles del proyecto, mensajes o archivos que envíes voluntariamente.</li>
                <li>Datos técnicos: dirección IP, tipo de navegador, dispositivo y registros del servidor (usados solo para fines de seguridad y diagnóstico).</li>
            </ul>
            <p>
                <strong>No recopilamos</strong> números de documentos (como DNI, NIE o pasaporte), ni datos financieros o de carácter sensible.
            </p>

            <h2>2. Finalidad del tratamiento y base legal</h2>
            <ul>
                <li><strong>Prestación del servicio:</strong> elaborar y enviar presupuestos solicitados por el usuario.</li>
                <li><strong>Comunicación:</strong> responder a consultas, gestionar solicitudes y ofrecer asistencia al cliente.</li>
                <li><strong>Mejora del servicio:</strong> analizar de forma anónima el uso del sistema para optimizar su funcionamiento (previo consentimiento, cuando sea necesario).</li>
                <li><strong>Cumplimiento legal:</strong> cumplir obligaciones fiscales o legales cuando proceda.</li>
            </ul>

            <h2>3. Periodo de conservación</h2>
            <p>
                Conservamos los datos personales solo durante el tiempo necesario para los fines descritos:
            </p>
            <ul>
                <li>Datos de presupuestos y comunicación: hasta 5 años después de la última interacción, salvo obligación legal distinta.</li>
                <li>Datos técnicos y registros de servidor: por un periodo limitado para fines de seguridad (normalmente unos meses).</li>
            </ul>

            <h2>4. Compartición de datos</h2>
            <p>
                No vendemos tus datos personales. Podemos compartirlos únicamente con:
            </p>
            <ul>
                <li>Proveedores que nos prestan servicios técnicos (por ejemplo, alojamiento web, envío de correos electrónicos o soporte técnico), quienes actúan bajo contrato y confidencialidad.</li>
                <li>Autoridades competentes si es requerido por ley o por orden judicial.</li>
            </ul>

